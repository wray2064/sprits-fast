int pixelFontLineHeight() {
    return kRows + 2;
}

std::vector<ls::Vec2i> layOutText(const std::string& text, ls::Vec2i at, int scale,
                                  int* widthOut, int* heightOut) {
    std::vector<ls::Vec2i> pixels;
    scale = std::clamp(scale, 1, 16);
    int x = 0;
    int y = 0;
    int widest = 0;
    int lines = 1;
    for (char c : text) {
        if (c == '\n') {
            widest = std::max(widest, x);
            x = 0;
            y += pixelFontLineHeight();
            ++lines;
            continue;
        }
        const Glyph* glyph = glyphFor(c);
        if (glyph == nullptr) {
            glyph = glyphFor('?');          // a character the face lacks
        }
        const int width = widthOf(*glyph);
        for (int row = 0; row < kRows; ++row) {
            const char* line = glyph->rows[row];
            for (int column = 0; line[column] != '\0'; ++column) {
                if (line[column] != '#') {
                    continue;
                }
                for (int sy = 0; sy < scale; ++sy) {
                    for (int sx = 0; sx < scale; ++sx) {
                        pixels.push_back({ at.x + (x + column) * scale + sx,
                                           at.y + (y + row) * scale + sy });
                    }
                }
            }
        }
        x += width + 1;                     // one pixel between letters
    }
    widest = std::max(widest, x > 0 ? x - 1 : 0);
    if (widthOut != nullptr) {
        *widthOut = widest * scale;
    }
    if (heightOut != nullptr) {
        *heightOut = ((lines - 1) * pixelFontLineHeight() + kRows) * scale;
    }
    return pixels;
}

