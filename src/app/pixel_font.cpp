const Glyph* glyphFor(char c) {
    for (const Glyph& glyph : kGlyphs) {
        if (glyph.c == c) {
            return &glyph;
        }
    }
    return nullptr;
}

int widthOf(const Glyph& glyph) {
    int width = 0;
    for (const char* row : glyph.rows) {
        width = std::max(width, static_cast<int>(std::char_traits<char>::length(row)));
    }
    return width;
}

